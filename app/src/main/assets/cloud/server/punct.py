# -*- coding: utf-8 -*-
"""v3.170 — ЗАПЯТЫЕ В ПОРОЖДЁННОМ ТЕКСТЕ.

Владелец: «написал он всё правильно, если расставить запятые». Мозг и своя
LLM собирают фразы из слов без знаков препинания внутри предложения.
Здесь — правила русской пунктуации для самых частых случаев (запятая перед
подчинительными союзами и союзными словами, перед «а», «но», «однако»),
без изменения слов. Применяется ТОЛЬКО к порождённому тексту (речь мозга,
своя LLM), не к цитатам источников.
"""
import re

# перед этими словами внутри предложения нужна запятая
_SUB = ("что", "чтобы", "который", "которая", "которое", "которые", "которого",
        "которой", "которым", "которых", "которую", "если", "хотя", "потому",
        "поэтому", "пока", "где", "куда", "откуда", "когда", "почему", "зачем",
        "чем", "словно", "будто", "ведь", "однако", "но", "а", "зато",
        "причём", "притом", "сколько", "как")
# …но не после этих слов (союз составной или слово — не союз)
_NO_AFTER = {"потому", "так", "то", "тот", "того", "том", "тем", "ни", "не",
             "и", "или", "либо", "да", "а", "но", "кроме", "раньше", "прежде",
             "после", "несмотря", "лишь", "только", "вот", "всё", "все",
             "это", "ничего", "кое", "по", "в", "на", "с", "за", "о", "об",
             "при", "до", "из", "от", "для", "про", "через", "без", "под",
             "над", "между", "чем", "что", "как", "тогда", "именно", "даже",
             "уже", "ещё", "еще", "так", "такой", "такая", "такое", "такие",
             "столько", "сам", "сама", "оттого", "затем", "зачем"}
# «как» — только в сравнениях после «так/такой» уже без запятой; одиночное
# «как» в середине часто вводит придаточное («знаю, как сделать»)
_WORD = re.compile(r"\S+")


def fix(text):
    """Расставить запятые перед союзами внутри предложений."""
    out = []
    for sent in re.split(r"(?<=[.!?…])\s+", str(text or "")):
        toks = sent.split(" ")
        res = []
        for i, tok in enumerate(toks):
            w = re.sub(r"[^а-яёa-z-]", "", tok.lower())
            if i >= 2 and w in _SUB and res:
                prev_raw = res[-1]
                prev = re.sub(r"[^а-яёa-z-]", "", prev_raw.lower())
                if prev and prev not in _NO_AFTER and not re.search(r"[,;:—–(-]$", prev_raw) \
                        and not (w == "как" and prev in ("так", "такой", "такая", "такое")) \
                        and not (w in ("а", "но") and i == len(toks) - 1):
                    res[-1] = prev_raw + ","
            res.append(tok)
        s = " ".join(res)
        s = re.sub(r"\s+-\s+", " — ", s)              # «какого - либо» -> тире
        s = re.sub(r"(\w)\s—\s(либо|нибудь|то)\b", r"\1-\2", s)  # …кроме «какого-либо»
        out.append(s)
    return " ".join(out)
