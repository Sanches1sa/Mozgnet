add("fn.graph", "Как нарисовать график функции в приложении",
    ["рисовать графики функций", "график функции приложение app lab", "построить график y=x^2", "нарисуй график навык", "ctx.draw.graph"],
    """Рисует график сам облачный движок: ctx.draw.graph(выражение, x0, x1) возвращает строку с картинкой [КАРТИНКА]<svg>[/КАРТИНКА] — чат её показывает.
Выражение считается безопасно (белый список: + - * / ^, скобки, sin cos tan sqrt log exp pi), exec и eval не используются.
Приложению остаётся разобрать фразу: выражение после «y=» или слова «график» и границы «от a до b». Нечитаемое выражение — честная подсказка вместо трассировки.
Не берите из интернета код на tkinter/matplotlib: в облаке нет окон, а сторонние библиотеки могут отсутствовать.""",
    '''
import re


def run(text, ctx):
    """App Lab: рисовать графики функций"""
    low = text.lower().replace(",", ".").replace("²", "^2").replace("π", "pi")
    m = re.search(r"y\\s*=\\s*([^а-я]+?)(?:\\s+от\\s|$)", low) or re.search(r"график[а-я]*\\s+(?:функции\\s+)?([^а-я]+?)(?:\\s+от\\s|$)", low)
    if not m:
        return "Скажите, например: «график y=x^2 от -3 до 3» или «график sin(x)»."
    expr = m.group(1).strip().rstrip(".!?")
    rng = re.search(r"от\\s*(-?\\d+(?:\\.\\d+)?)\\s*до\\s*(-?\\d+(?:\\.\\d+)?)", low)
    x0, x1 = (float(rng.group(1)), float(rng.group(2))) if rng else (-6.0, 6.0)
    try:
        return ctx.draw.graph(expr, x0, x1)
    except Exception as e:
        return "Не получилось построить график: %s" % e
''', "график y=x^2 от -3 до 3", "[КАРТИНКА]", triggers=["график", "графики", "построй график", "нарисуй график"])

