CURRICULUM = LANG + LOGIC + MATH + WORLD + DIALOG + SYSTEM


def load_into_kb():
    """Загрузить все статьи программы в базу знаний."""
    import kb
    n = 0
    for title, text in CURRICULUM:
        try:
            r = kb.add_article(title, text, source="программа обучения")
            if r and r.get("ok"):
                n += 1
        except Exception:
            pass
    return n


def start_training():
    """Загрузить программу и запустить обучение (без сброса уже выученного)."""
    n = load_into_kb()
    try:
        import learnall
        st = learnall.start({"full": False, "why": "программа обучения с нуля"})
    except Exception as e:
        return {"ok": False, "loaded": n, "error": str(e)[:200]}
    return {"ok": True, "loaded": n, "articles": len(CURRICULUM),
            "sections": ["язык", "логика", "числа", "мир", "диалог", "система"],
            "status": st}
