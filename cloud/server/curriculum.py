def groups():
    """Темы программы с размерами — для страницы «Сопряжение».

    Возвращает список пар (название блока, число уроков) по всем блокам,
    кроме сборных (CURRICULUM).
    """
    import sys as _sys
    module = _sys.modules[__name__]
    names = ("LANG LOGIC MATH WORLD DIALOG SYSTEM SECURITY ADMIN NETWORK "
             "EXTRA_SECURITY EXTRA_ADMIN EXTRA_NETWORK "
             "EXTRA_SECURITY2 EXTRA_ADMIN2 EXTRA_NETWORK2 CODE").split()
    titles = {"LANG": "Язык", "LOGIC": "Логика", "MATH": "Числа",
              "WORLD": "Мир", "DIALOG": "Диалог", "SYSTEM": "Система",
              "SECURITY": "Информационная безопасность",
              "ADMIN": "Администрирование серверов", "NETWORK": "Сети и зоны",
              "EXTRA_SECURITY": "ИБ: продолжение",
              "EXTRA_ADMIN": "Администрирование: продолжение",
              "EXTRA_NETWORK": "Сети: продолжение",
              "EXTRA_SECURITY2": "ИБ: облако, утечки, учения",
              "EXTRA_ADMIN2": "Администрирование: диски, службы, обновления",
              "EXTRA_NETWORK2": "Сети: диагностика и файрвол",
              "CODE": "Код и данные"}
    out = []
    for name in names:
        block = getattr(module, name, None)
        if isinstance(block, (list, tuple)):
            out.append((titles.get(name, name), len(block)))
